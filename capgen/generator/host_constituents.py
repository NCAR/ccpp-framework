def _generate_host_constituents(
    suite_results: List[SuiteResolution],
    host_dict=None,
) -> Optional[List[str]]:
    """Generate ``ccpp_host_constituents.F90`` source lines, or ``None``."""
    if not _any_constituent_state(suite_results):
        return None

    register_suites = _suites_with_register_consts(suite_results)
    index_names     = _all_index_names(suite_results)

    lines: List[str] = []
    lines.append(
        '! ccpp_host_constituents.F90 -- generated by ccpp_capgen, do not edit'
    )
    lines.append('module {}'.format(_HOST_CONST_MOD))
    lines.append('')
    lines.append('{}use ccpp_kinds, only: kind_phys'.format(_INDENT))
    lines.append('{}use {}, only: &'.format(_INDENT, _CONST_PROP_MOD))
    lines.append('{}{}, &'.format(_INDENT * 2, _CONST_DDT))
    lines.append('{}{}, &'.format(_INDENT * 2, _CONST_PROP_TYPE))
    lines.append('{}{}, &'.format(_INDENT * 2, _CONST_PROP_PTR_TYPE))
    # int_unassigned is the sentinel returned by %const_index when a
    # standard name is not in the constituent table.  Used by
    # ccpp_initialize_constituents to validate that every cached
    # index_of_<X> integer corresponds to an actually-registered
    # constituent — surfaces missing-registration bugs at init time
    # instead of letting them become silent invalid array accesses
    # later in run-phase scheme calls.
    lines.append('{}int_unassigned'.format(_INDENT * 2))
    lines.append('')
    lines.append('{}implicit none'.format(_INDENT))
    lines.append('{}private'.format(_INDENT))
    lines.append('')

    # Publics: state + routines.
    publics = [_CONST_OBJ]
    publics += [_index_symbol_name(n) for n in index_names]
    publics += [
        'ccpp_register_constituents',
        'ccpp_initialize_constituents',
        'ccpp_is_scheme_constituent',
        'ccpp_number_constituents',
        'ccpp_gather_constituents',
        'ccpp_update_constituents',
        'ccpp_const_get_index',
        'ccpp_constituents_array',
        'ccpp_advected_constituents_array',
        'ccpp_model_const_properties',
        'ccpp_deallocate_dynamic_constituents',
    ]
    if index_names:
        publics.append('ccpp_model_const_stdnames')
    publics += [_dyn_const_array_name(s) for s in register_suites]
    for p in publics:
        lines.append('{}public :: {}'.format(_INDENT, p))
    lines.append('')

    # Per-instance wrapper around the per-suite scheme-registered
    # constituent buffer.  Each instance owns its own slot in the outer
    # array; the inner ``items(:)`` array is filled independently by
    # ``<suite>_register`` per instance so that the property objects
    # (which acquire a const_ind during ``ccpp_register_constituents``)
    # are not shared across instances.
    if register_suites:
        lines.append(
            '{}type :: ccpp_dyn_const_buffer_t'.format(_INDENT)
        )
        lines.append(
            '{}type({}), allocatable :: items(:)'.format(
                _INDENT * 2, _CONST_PROP_TYPE,
            )
        )
        lines.append(
            '{}end type ccpp_dyn_const_buffer_t'.format(_INDENT)
        )
        lines.append('')

    # State declarations.
    lines.append(
        '{}type({}), target, allocatable :: {}(:)'.format(
            _INDENT, _CONST_DDT, _CONST_OBJ,
        )
    )
    lines.append('')
    for sname in register_suites:
        buf = _dyn_const_array_name(sname)
        lines.append(
            '{}type(ccpp_dyn_const_buffer_t), allocatable, target :: {}(:)'.format(
                _INDENT, buf,
            )
        )
    if register_suites:
        lines.append('')
    # Default to int_unassigned (NOT 0) so a constituent that is referenced
    # by a scheme but never bound by ccpp_initialize_constituents (missing
    # registration, or a host that never calls the init routine) is caught
    # by the post-const_index guard below instead of silently surviving as
    # an index of 0 and producing an out-of-bounds vars_layer subscript at
    # run time.  This also keeps the guard correct for any framework whose
    # %const_index leaves the output unchanged on a name miss.
    for std_name in index_names:
        lines.append('{}integer :: {} = int_unassigned'.format(
            _INDENT, _index_symbol_name(std_name)))
    if index_names:
        max_len = max(len(n) for n in index_names)
        lines.append('')
        lines.append(
            '{}character(len={}), parameter :: ccpp_model_const_stdnames({}) = (/ &'.format(
                _INDENT, max_len, len(index_names),
            )
        )
        for i, std_name in enumerate(index_names):
            sep = ', &' if i < len(index_names) - 1 else ' /)'
            padding = ' ' * (max_len - len(std_name))
            lines.append("{}'{}{}'{}".format(_INDENT * 2, std_name, padding, sep))
    lines.append('')
    lines.append('contains')

    lines.extend(_register_constituents_lines(suite_results, host_dict))
    lines.extend(_initialize_constituents_lines(suite_results, host_dict))
    lines.extend(_is_scheme_constituent_lines(suite_results))
    lines.extend(_wrap_method_subs(host_dict))
    lines.extend(_accessor_functions(host_dict))
    lines.extend(_deallocate_lines(suite_results, host_dict))

    lines.append('')
    lines.append('end module {}'.format(_HOST_CONST_MOD))
    return lines


def write_host_constituents(
    suite_results: List[SuiteResolution],
    outdir: str,
    host_dict=None,
    logger: Optional[logging.Logger] = None,
) -> Optional[str]:
    """Write ``ccpp_host_constituents.F90`` if needed, return its path or ``None``."""
    lines = _generate_host_constituents(suite_results, host_dict)
    if lines is None:
        return None
    if not os.path.isdir(outdir):
        os.makedirs(outdir, exist_ok=True)
    path = os.path.join(outdir, 'ccpp_host_constituents.F90')
    with open_if_changed(path, logger=logger) as fh:
        fh.write('\n'.join(lines) + '\n')
    return os.path.abspath(path)
